# 이 줄을 왼쪽부터 읽으면(한 줄에 세 가지가 겹쳐 있어서 끊어서 읽어야 함)
# sorted(pairs, key=lambda t: -t[1]) -> pairs를 줄 세운 새 목록을 만듦(원본은 유지)
# key=lambda t: -t[1] -> 무엇을 기준으로 줄 세울지를 알려주는 손잡이
# lambda t: -t[1] -> 이름 없는 한 줄 함수, 't를 받으면 -t[1]을 돌려준다'는 뜻
# t는 (이름, 값) 같은 한 쌍이고 t[1]은 그 쌍의 숫자임
# 앞에 붙은 -는 작은 것부터 세우는 것이 기본이라, 부호를 뒤집어 큰 것부터 세움


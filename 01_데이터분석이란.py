# 1) 859.53 <- .2f = 소수 둘째 자리까지 출력 |      859.5 <- 10칸 폭, 첫째 자리 |    44 <- 정수 5칸 오른쪽 | 0.5% <-0.00455를 퍼센트로

# {x:.2f} -> 소수 둘쨰 자리까지만 보여 달라, 859.5318 -> 859.53으로 보임
# {x:10.1f} -> 10칸을 잡고 그 안에서 첫째 자리까지, 모자란 칸은 왼쪽이 공백으로 찍힘
# 표의 세로 줄을 맞추려고 쓰는 손잡이(밑에 9번에서 실제로 쓸 예정)

# {44:>5d} -> d는 정수, 5는 칸 폭, >는 그 칸에서 오른쪽에 붙이라는 뜻
# {0.00455:.1%} -> 퍼센트로 보여 달라, 100를 곱하고 %를 붙여서 4.5%


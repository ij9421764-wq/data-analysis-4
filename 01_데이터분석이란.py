# 같은 계산을 배치마다 3번 해야 하니, 함수로 만들어 둘 것임


def stat(values):
    """
    숫자 리스트를 받아 개수, 평균, 최대, 최소, 범위, 흔들림을 딕셔너리로 돌려줌
    왜 딕셔너리로 돌려주는가? - 값 6개를 튜플로 돌려주면 받는 쪽에서 순서를 기억해야 함
    s[3]이 최소인지, 범위인지, 몇 일후에는 모름(돌려줄 때 딕셔너리를 사용하는 이유)
    딕셔너리면 s['최소']라고 쓰게 되어 코드가 스스로 설명함
    """
    m = sum(values) / len(values)
    top = max(values)
    low = min(values)
    span = top - low

    return {
        "개수": len(values),
        "평균": round(m, 2),
        "최대": top,
        "최소": low,
        "범위": round(span, 2),
        "흔들림": round(sum(abs(v - m) for v in values) / len(values), 2),
    }



import csv
import os  # 파일 경로를 다루는 파이썬 기본 모듈


def dp(name):
    # 아래와 같이 """를 사용하는 것이 AI와의 차이점
    # 소스트리는 배우지 않아도 됨
    """
    실행 위치가 어디든 data 폳더를 찾아주는 작은 도우미 함수
    "data/17_열처리.csv" 지금 있는 폴더 아래의 data를 뜻함.
    그래서 터미널이 어느 폴더에 있느냐에 따라 같은 코드가 되기도 하고
    FileNotFoundError가 나기도 함
    폴더 배치 posco_data_analysis_4/data 밑에 있음
    """

    here = os.path.dirname(os.path.abspath(__file__))

    for c in (
        os.path.join("data", name),
        os.path.join(here, "data", name),
        os.path.join(here, "..", "data", name),
    ):
        if os.path.exists(c):
            return c
    return os.path.join("data", name)


